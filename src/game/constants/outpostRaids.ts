/**
 * Рейды на постройки.
 *
 * До этого аванпост был чистым плюсом без риска: построил и забыл. Захват
 * даёт системе то, чего ей не хватало, — что-то, что можно потерять.
 * Постройка при этом не уничтожается: её отбивают, и потому неудача стоит
 * времени и боя, а не забега.
 */

/**
 * Базовый шанс захвата за ход, до всех множителей.
 *
 * Число выглядит крошечным намеренно: за забег в 150 ходов оно копится.
 * Первая версия давала 1.2% за ход — то есть 84% шанс потерять постройку
 * хотя бы раз, а на четвёртом тире 99%. Это уже не риск, а расписание.
 * Ориентир: тир 1 ≈ 18% за забег, тир 4 ≈ 39%, с турелями и стрелком ≈ 11%.
 */
export const RAID_BASE_CHANCE = 0.0013;

/** Множитель шанса по тиру сектора: чем глубже, тем злее соседи */
export const RAID_TIER_MULTIPLIER = [1, 1, 1.4, 1.9, 2.5] as const;

/** Кризис рейдерской волны поднимает шанс кратно */
export const RAID_CRISIS_MULTIPLIER = 2.5;
export const RAID_CRISIS_ID = "raider_wave";

/** Модификатор «В розыске» приводит к постройкам тех, кто ищет вас */
export const RAID_WANTED_MULTIPLIER = 1.8;

/** Охранник в гарнизоне снижает шанс */
export const RAID_GUARD_PROTECTION = 0.6;

/**
 * Льготный период — после закладки и после каждого отбития.
 *
 * Без второго случая отбитую постройку могли захватить на следующем же ходу,
 * и штурм превращался в бесконечную карусель.
 */
export const RAID_GRACE_TURNS = 15;

/** Сила рейдеров зависит от тира сектора */
export const RAID_THREAT_BY_TIER = [1, 2, 3, 4, 5] as const;
